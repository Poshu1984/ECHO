// Regenerates src/brandMascots.js from public/brand/mascots/*-{hello,focus,celebrate}.svg
// (brand CI v2). Body shapes keep their brand colors; face shapes (eyes,
// mouth) are split out so the story stage can blink and lip-sync them.
import { readFileSync, writeFileSync } from "node:fs";

// Face colour per character (eyes and mouth are drawn in it).
const FACE = {
  koto: ["#FFFFFF"], pip: ["#D9F36B"], nami: ["#FAF8F2"],
  leo: ["#FFFFFF"], sol: ["#212033"], mo: ["#FAF8F2"], mira: ["#FFFFFF"],
};
const ATTR = /([a-zA-Z-]+)="([^"]*)"/g;
const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function parse(file, faceColors) {
  const text = readFileSync(file, "utf8");
  const items = [];
  for (const m of text.matchAll(/<(path|ellipse|circle|rect)\s([^>]*?)\/>/g)) {
    const attrs = {};
    for (const [, k, v] of m[2].matchAll(ATTR)) attrs[camel(k)] = v;
    const color = (attrs.fill && attrs.fill !== "none" ? attrs.fill : attrs.stroke || "").toUpperCase();
    items.push({ tag: m[1], attrs, face: faceColors.includes(color) });
  }
  return items;
}

function center(item) {
  const a = item.attrs;
  if (item.tag === "ellipse" || item.tag === "circle") return [Number(a.cx), Number(a.cy)];
  const nums = (a.d || "").match(/-?\d+(\.\d+)?/g).map(Number);
  const xs = nums.filter((_, i) => i % 2 === 0);
  const ys = nums.filter((_, i) => i % 2 === 1);
  return [(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2];
}

const out = {};
for (const id of Object.keys(FACE)) {
  const looks = {};
  let faceColor = "#FFFFFF";
  for (const look of ["hello", "focus", "celebrate"]) {
    const items = parse(`public/brand/mascots/${id}-${look}.svg`, FACE[id]);
    const face = items.filter((i) => i.face);
    const mouth = face[face.length - 1];
    faceColor = (mouth.attrs.stroke && mouth.attrs.stroke !== "none" ? mouth.attrs.stroke : mouth.attrs.fill);
    looks[look] = {
      body: items.filter((i) => !i.face).map(({ tag, attrs }) => ({ tag, attrs })),
      eyes: face.slice(0, -1).map(({ tag, attrs }) => ({ tag, attrs })),
      mouth: { tag: mouth.tag, attrs: mouth.attrs },
      mouthCenter: center(mouth),
    };
  }
  out[id] = { viewBox: "0 0 240 270", faceColor, looks };
}

writeFileSync(
  "src/brandMascots.js",
  `// Generated by scripts/build-mascots.mjs from the brand CI v2 mascot SVGs. Do not edit by hand.\nexport const MASCOTS = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("wrote src/brandMascots.js");
